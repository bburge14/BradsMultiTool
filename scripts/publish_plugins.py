#!/usr/bin/env python3
"""Publish the separate plugins to their own repositories (the Plugin Hub builds each from its own repo).

Development stays in this repository. Each plugins/<folder> here is already a complete plugin repository
(generated by split_plugins.py and committed). This script copies each folder, exactly as committed at HEAD,
into the repository named for it in publish.json, commits ("Update from BradsMultiTool <commit>: <message>")
and pushes. Then it writes the Plugin Hub entry for each (releases/plugin-hub/<name>: repository= and commit=),
and with "pluginHubFork" set, puts them on a branch of your fork of runelite/plugin-hub ready for a pull request.

Usage:
    python3 scripts/publish_plugins.py                  # every plugin with "publish": true in publish.json
    python3 scripts/publish_plugins.py skilling-helper  # just these folders
    python3 scripts/publish_plugins.py --dry-run        # do everything but push (shows what would change)
    python3 scripts/publish_plugins.py --no-hub         # skip the plugin-hub fork branch
    python3 scripts/publish_plugins.py --config other.json   # another mapping (for testing)

Before publishing it checks: the working tree is clean, HEAD is pushed, and plugins/ matches src/
(split_plugins.py --check). Needs git and Python 3; pushing uses your own git login.
"""
import io
import json
import os
import shutil
import subprocess
import sys
import tarfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CONFIG = os.path.join(ROOT, "publish.json")
CACHE = os.path.join(ROOT, ".publish-cache")
HUB_OUT = os.path.join(ROOT, "releases", "plugin-hub")


def git(*args, cwd=ROOT, capture=True, check=True):
    result = subprocess.run(["git", *args], cwd=cwd, check=False, text=True,
                            stdout=subprocess.PIPE if capture else None, stderr=subprocess.PIPE if capture else None)
    if check and result.returncode != 0:
        sys.exit("git %s failed in %s:\n%s" % (" ".join(args), cwd, (result.stderr or "").strip()))
    return (result.stdout or "").strip()


def preflight(dry_run):
    if git("status", "--porcelain"):
        sys.exit("Commit (or stash) your changes first: publishing uses what's committed.")
    check = subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "split_plugins.py"), "--check"], cwd=ROOT)
    if check.returncode != 0:
        sys.exit("plugins/ is out of date: run python3 scripts/split_plugins.py --verify, commit, and try again.")
    if not dry_run:
        git("fetch", "--quiet", "origin")
        upstream = git("rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}", check=False)
        if upstream and git("rev-list", "--count", upstream + "..HEAD") != "0":
            sys.exit("Push this repository first (" + upstream + " is behind HEAD), so each update names a commit "
                     "that exists here.")


def checkout(name, repo, branch, dry_run):
    """A clone of the plugin's repository in .publish-cache, on its branch, matching the remote."""
    path = os.path.join(CACHE, name)
    if not os.path.isdir(os.path.join(path, ".git")):
        os.makedirs(CACHE, exist_ok=True)
        if subprocess.run(["git", "clone", "--quiet", repo, path]).returncode != 0:
            sys.exit("Couldn't clone %s. Make the repository on GitHub first (it can be empty)." % repo)
    git("remote", "set-url", "origin", repo, cwd=path)
    git("fetch", "--quiet", "origin", cwd=path, check=False)
    if git("ls-remote", "--heads", "origin", branch, cwd=path):
        git("checkout", "--quiet", "-B", branch, "origin/" + branch, cwd=path)
    else:
        # A new, empty repository: start the branch
        git("checkout", "--quiet", "--orphan", branch, cwd=path, check=False)
    return path


def replace_contents(folder, path):
    """Make the clone's files exactly plugins/<folder> as committed at HEAD."""
    for entry in os.listdir(path):
        if entry == ".git":
            continue
        full = os.path.join(path, entry)
        shutil.rmtree(full) if os.path.isdir(full) and not os.path.islink(full) else os.remove(full)
    data = subprocess.run(["git", "archive", "--format=tar", "HEAD:plugins/" + folder], cwd=ROOT,
                          stdout=subprocess.PIPE, check=True).stdout
    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        tar.extractall(path)


def publish(folder, entry, dry_run, head, subject):
    name = entry["hubName"]
    repo = entry["repo"]
    branch = entry.get("branch", "master")
    path = checkout(name, repo, branch, dry_run)
    replace_contents(folder, path)
    git("add", "-A", cwd=path)
    if not git("status", "--porcelain", cwd=path):
        print("%-18s no changes since the last publish" % folder)
    else:
        changed = len(git("status", "--porcelain", cwd=path).splitlines())
        git("commit", "--quiet", "-m", "Update from BradsMultiTool %s: %s" % (head[:7], subject), cwd=path)
        if dry_run:
            print("%-18s %d file(s) would change (dry run: not pushed)" % (folder, changed))
        else:
            git("push", "--quiet", "origin", branch, cwd=path, capture=False)
            print("%-18s pushed %d changed file(s) to %s" % (folder, changed, repo))
    commit = git("rev-parse", "HEAD", cwd=path)
    os.makedirs(HUB_OUT, exist_ok=True)
    with open(os.path.join(HUB_OUT, name), "w") as f:
        f.write("repository=%s\ncommit=%s\n" % (repo, commit))
    return name


def update_hub_fork(fork, names, dry_run, head):
    """Put the Plugin Hub entries on a branch of your plugin-hub fork, ready for a pull request."""
    path = os.path.join(CACHE, "plugin-hub")
    if not os.path.isdir(os.path.join(path, ".git")):
        os.makedirs(CACHE, exist_ok=True)
        if subprocess.run(["git", "clone", "--quiet", "--depth", "50", fork, path]).returncode != 0:
            sys.exit("Couldn't clone your plugin-hub fork %s (fork runelite/plugin-hub on GitHub first)." % fork)
    if not git("remote", cwd=path).count("upstream"):
        git("remote", "add", "upstream", "https://github.com/runelite/plugin-hub.git", cwd=path)
    git("fetch", "--quiet", "--depth", "50", "upstream", "master", cwd=path)
    branch = "snuffys-" + head[:7]
    git("checkout", "--quiet", "-B", branch, "upstream/master", cwd=path)
    for name in names:
        shutil.copy(os.path.join(HUB_OUT, name), os.path.join(path, "plugins", name))
    git("add", "-A", cwd=path)
    if not git("status", "--porcelain", cwd=path):
        print("plugin-hub: entries already up to date")
        return
    git("commit", "--quiet", "-m", "Update Snuffy's plugins (" + ", ".join(names) + ")", cwd=path)
    if dry_run:
        print("plugin-hub: branch %s ready (dry run: not pushed)" % branch)
        return
    git("push", "--quiet", "-f", "origin", branch, cwd=path, capture=False)
    owner = fork.rstrip("/").removesuffix(".git").split("/")[-2]
    print("plugin-hub: pushed branch %s. Open the pull request:\n  https://github.com/runelite/plugin-hub/compare/"
          "master...%s:plugin-hub:%s" % (branch, owner, branch))


def main():
    argv = sys.argv[1:]
    config_path = CONFIG
    if "--config" in argv:
        i = argv.index("--config")
        config_path = os.path.abspath(argv[i + 1])
        del argv[i:i + 2]
    args = [a for a in argv if not a.startswith("--")]
    dry_run = "--dry-run" in argv
    with open(config_path) as f:
        config = json.load(f)
    plugins = config["plugins"]
    chosen = args or [folder for folder, entry in plugins.items() if entry.get("publish")]
    unknown = [c for c in chosen if c not in plugins]
    if unknown:
        sys.exit("Not in publish.json: " + ", ".join(unknown))
    if not chosen:
        sys.exit('Nothing to publish: set "publish": true for a plugin in publish.json (and its "repo").')
    preflight(dry_run)
    head = git("rev-parse", "HEAD")
    subject = git("log", "-1", "--format=%s")
    names = [publish(folder, plugins[folder], dry_run, head, subject) for folder in chosen]
    print("Plugin Hub entries written to releases/plugin-hub/")
    fork = config.get("pluginHubFork")
    if fork and "--no-hub" not in sys.argv:
        update_hub_fork(fork, names, dry_run, head)


if __name__ == "__main__":
    main()
