#!/usr/bin/env python3
"""Push the separate plugins to their own repositories, and publish them to RuneLite's Plugin Hub.

Development stays in this repository. Each plugins/<folder> here is already a complete plugin (generated by
split_plugins.py and committed). Two steps:

  push     Copies each plugin's folder, exactly as committed at HEAD, into its repository (publish.json). A plugin
           that changed gets its next version (patch by default; --bump minor or --bump major), written into its
           build.gradle, a commit "<name> <version>" listing the changes since its last push, and a tag v<version>.
           A plugin that didn't change is left alone.
  hub      Writes each plugin's Plugin Hub entry (repository= and commit=, the commit its repository is at now) to
           releases/plugin-hub/, and puts them on a branch of your runelite/plugin-hub fork; prints the link to
           open the pull request. This is what makes RuneLite build the new version for players.

Usage:
    python3 scripts/publish_plugins.py push [folders...] [--bump patch|minor|major] [--dry-run]
    python3 scripts/publish_plugins.py hub  [folders...] [--dry-run]
    (no folders: every plugin with "publish": true in publish.json; --config other.json for another mapping)

push first checks the working tree is clean, pushed, and plugins/ matches src/. Needs git and Python 3; pushing
uses your own git login.
"""
import io
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CONFIG = os.path.join(ROOT, "publish.json")
CACHE = os.path.join(ROOT, ".publish-cache")
HUB_OUT = os.path.join(ROOT, "releases", "plugin-hub")


def git(*args, cwd=ROOT, capture=True, check=True):
    result = subprocess.run(["git", *args], cwd=cwd, check=False, text=True,
                            stdout=subprocess.PIPE if capture else None, stderr=subprocess.PIPE if capture else None)
    if check and result.returncode != 0:
        sys.exit("git %s failed in %s:\n%s" % (" ".join(args), cwd, (result.stderr or "").strip()))
    return (result.stdout or "").strip()


def preflight(dry_run):
    if git("status", "--porcelain"):
        sys.exit("Commit (or stash) your changes first: publishing uses what's committed.")
    check = subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "split_plugins.py"), "--check"], cwd=ROOT)
    if check.returncode != 0:
        sys.exit("plugins/ is out of date: run python3 scripts/split_plugins.py --verify, commit, and try again.")
    if not dry_run:
        git("fetch", "--quiet", "origin")
        upstream = git("rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}", check=False)
        if upstream and git("rev-list", "--count", upstream + "..HEAD") != "0":
            sys.exit("Push this repository first (" + upstream + " is behind HEAD), so each update names a commit "
                     "that exists here.")


def checkout(name, repo, branch, dry_run):
    """A clone of the plugin's repository in .publish-cache, on its branch, matching the remote."""
    path = os.path.join(CACHE, name)
    if not os.path.isdir(os.path.join(path, ".git")):
        os.makedirs(CACHE, exist_ok=True)
        if subprocess.run(["git", "clone", "--quiet", repo, path], stderr=subprocess.DEVNULL).returncode != 0:
            sys.exit("Couldn't clone %s. Make the repository on GitHub first (it can be empty)." % repo)
    git("remote", "set-url", "origin", repo, cwd=path)
    git("fetch", "--quiet", "origin", cwd=path, check=False)
    if git("ls-remote", "--heads", "origin", branch, cwd=path):
        git("checkout", "--quiet", "-B", branch, "origin/" + branch, cwd=path)
    else:
        # A new, empty repository: start the branch from nothing (dropping anything a dry run committed here)
        shutil.rmtree(path)
        if subprocess.run(["git", "clone", "--quiet", repo, path], stderr=subprocess.DEVNULL).returncode != 0:
            sys.exit("Couldn't clone %s." % repo)
        git("checkout", "--quiet", "--orphan", branch, cwd=path, check=False)
    return path


def replace_contents(folder, path):
    """Make the clone's files exactly plugins/<folder> as committed at HEAD."""
    for entry in os.listdir(path):
        if entry == ".git":
            continue
        full = os.path.join(path, entry)
        shutil.rmtree(full) if os.path.isdir(full) and not os.path.islink(full) else os.remove(full)
    data = subprocess.run(["git", "archive", "--format=tar", "HEAD:plugins/" + folder], cwd=ROOT,
                          stdout=subprocess.PIPE, check=True).stdout
    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        if hasattr(tarfile, "data_filter"):
            tar.extractall(path, filter="data")
        else:
            tar.extractall(path)


VERSION = re.compile(r"^version = '([^']+)'", re.M)


def read_version(path):
    gradle = os.path.join(path, "build.gradle")
    if not os.path.exists(gradle):
        return None
    with open(gradle, encoding="utf-8") as f:
        m = VERSION.search(f.read())
    return m.group(1) if m else None


def write_version(path, version):
    gradle = os.path.join(path, "build.gradle")
    with open(gradle, encoding="utf-8") as f:
        text = f.read()
    with open(gradle, "w", encoding="utf-8") as f:
        f.write(VERSION.sub("version = '%s'" % version, text, count=1))


def bump(version, level):
    """1.2.3 -> 1.2.4 (patch), 1.3.0 (minor), 2.0.0 (major)."""
    parts = [int(p) for p in re.findall(r"\d+", version)[:3]] + [0, 0, 0]
    major, minor, patch = parts[:3]
    if level == "major":
        return "%d.0.0" % (major + 1)
    if level == "minor":
        return "%d.%d.0" % (major, minor + 1)
    return "%d.%d.%d" % (major, minor, patch + 1)


def display_name(path):
    with open(os.path.join(path, "runelite-plugin.properties"), encoding="utf-8") as f:
        return re.search(r"^displayName=(.+)$", f.read(), re.M).group(1)


def changes_since(folder, last):
    """This repository's commit messages that changed plugins/<folder> since the last push (or the last 20)."""
    span = [last + "..HEAD"] if last and git("cat-file", "-t", last, check=False) == "commit" else ["-20"]
    lines = git("log", "--no-merges", "--format=- %s", *span, "--", "plugins/" + folder).splitlines()
    return lines or ["- Updated from BradsMultiTool"]


def push(folder, entry, dry_run, head, level):
    name = entry["hubName"]
    repo = entry["repo"]
    branch = entry.get("branch", "master")
    path = checkout(name, repo, branch, dry_run)
    old = read_version(path)
    # The last push's source commit, from its message
    last = re.search(r"BradsMultiTool ([0-9a-f]{7,40})", git("log", "-1", "--format=%B", cwd=path, check=False) or "")
    replace_contents(folder, path)
    # Compare with the version it had, so a version number alone isn't a change
    if old:
        write_version(path, old)
    git("add", "-A", cwd=path)
    if not git("status", "--porcelain", cwd=path):
        print("%-16s %s, no changes since the last push" % (folder, old))
        return
    new = bump(old, level) if old else read_version(path)
    write_version(path, new)
    git("add", "-A", cwd=path)
    changed = len(git("status", "--porcelain", cwd=path).splitlines())
    title = "%s %s" % (display_name(path), new)
    notes = changes_since(folder, last.group(1) if last else None)
    message = "%s\n\nFrom BradsMultiTool %s.\n\nChanges:\n%s\n" % (title, head[:12], "\n".join(notes))
    git("commit", "--quiet", "-m", message, cwd=path)
    git("tag", "-a", "-f", "v" + new, "-m", title, cwd=path)
    if dry_run:
        print("%-16s %s -> %s, %d file(s) would change (dry run: not pushed)" % (folder, old or "new", new, changed))
        for line in notes[:8]:
            print("                   " + line)
        return
    git("push", "--quiet", "origin", branch, "v" + new, cwd=path, capture=False)
    print("%-16s pushed %s (%d file(s) changed) to %s" % (folder, new, changed, repo))


def hub_entry(entry):
    """The Plugin Hub entry for a plugin: its repository and the commit its branch is at now."""
    branch = entry.get("branch", "master")
    head = git("ls-remote", entry["repo"], "refs/heads/" + branch, check=False).split()
    if not head:
        sys.exit("%s has nothing on %s yet: push first." % (entry["repo"], branch))
    os.makedirs(HUB_OUT, exist_ok=True)
    with open(os.path.join(HUB_OUT, entry["hubName"]), "w") as f:
        f.write("repository=%s\ncommit=%s\n" % (entry["repo"], head[0]))
    print("%-24s commit %s" % (entry["hubName"], head[0][:12]))
    return entry["hubName"]


def update_hub_fork(fork, names, dry_run, head):
    """Put the Plugin Hub entries on a branch of your plugin-hub fork, ready for a pull request."""
    path = os.path.join(CACHE, "plugin-hub")
    if not os.path.isdir(os.path.join(path, ".git")):
        os.makedirs(CACHE, exist_ok=True)
        if subprocess.run(["git", "clone", "--quiet", "--depth", "50", fork, path]).returncode != 0:
            sys.exit("Couldn't clone your plugin-hub fork %s (fork runelite/plugin-hub on GitHub first)." % fork)
    if not git("remote", cwd=path).count("upstream"):
        git("remote", "add", "upstream", "https://github.com/runelite/plugin-hub.git", cwd=path)
    git("fetch", "--quiet", "--depth", "50", "upstream", "master", cwd=path)
    branch = "snuffys-" + head[:7]
    git("checkout", "--quiet", "-B", branch, "upstream/master", cwd=path)
    for name in names:
        shutil.copy(os.path.join(HUB_OUT, name), os.path.join(path, "plugins", name))
    git("add", "-A", cwd=path)
    if not git("status", "--porcelain", cwd=path):
        print("plugin-hub: entries already up to date")
        return
    git("commit", "--quiet", "-m", "Update Snuffy's plugins (" + ", ".join(names) + ")", cwd=path)
    if dry_run:
        print("plugin-hub: branch %s ready (dry run: not pushed)" % branch)
        return
    git("push", "--quiet", "-f", "origin", branch, cwd=path, capture=False)
    owner = fork.rstrip("/").removesuffix(".git").split("/")[-2]
    print("plugin-hub: pushed branch %s. Open the pull request:\n  https://github.com/runelite/plugin-hub/compare/"
          "master...%s:plugin-hub:%s" % (branch, owner, branch))


def main():
    argv = sys.argv[1:]
    config_path = CONFIG
    if "--config" in argv:
        i = argv.index("--config")
        config_path = os.path.abspath(argv[i + 1])
        del argv[i:i + 2]
    level = "patch"
    if "--bump" in argv:
        i = argv.index("--bump")
        level = argv[i + 1]
        del argv[i:i + 2]
        if level not in ("patch", "minor", "major"):
            sys.exit("--bump is patch, minor or major")
    words = [a for a in argv if not a.startswith("--")]
    if not words or words[0] not in ("push", "hub"):
        sys.exit(__doc__)
    step, args = words[0], words[1:]
    dry_run = "--dry-run" in argv
    with open(config_path) as f:
        config = json.load(f)
    plugins = config["plugins"]
    chosen = args or [folder for folder, entry in plugins.items() if entry.get("publish")]
    unknown = [c for c in chosen if c not in plugins]
    if unknown:
        sys.exit("Not in publish.json: " + ", ".join(unknown))
    if not chosen:
        sys.exit('Nothing chosen: set "publish": true for a plugin in publish.json (and its "repo").')
    if step == "push":
        preflight(dry_run)
        head = git("rev-parse", "HEAD")
        for folder in chosen:
            push(folder, plugins[folder], dry_run, head, level)
        print("Done. When you're ready for players to get it: publish to RuneLite (the hub step).")
        return
    names = [hub_entry(plugins[folder]) for folder in chosen]
    print("Plugin Hub entries written to releases/plugin-hub/")
    fork = config.get("pluginHubFork")
    if fork:
        update_hub_fork(fork, names, dry_run, git("rev-parse", "HEAD"))


if __name__ == "__main__":
    main()
