#!/usr/bin/env python3
"""Write <Name>Defaults.java for each settings interface (code that saves every setting's default value), and
the copies of the shared settings in each plugin's settings interface.

Usage:
    python3 scripts/generate_config_defaults.py           # (re)write them
    python3 scripts/generate_config_defaults.py --check   # are they up to date? (changes nothing)

RuneLite only saves the defaults of the settings an interface declares itself (ConfigManager.setDefaultConfiguration
reads getDeclaredMethods), not ones it inherits. Every plugin's settings inherit theirs (CommonConfig, TickConfig,
and in the Toolbelt all of them), and the settings panel breaks on a choice (enum) setting with nothing saved, and
shows other unsaved settings wrong (a default-on switch as off). So each plugin saves them itself at start
(ConfigDefaults), through these classes: plain calls to each setting, since the Plugin Hub doesn't allow reflection.

RuneLite also caches settings by their Java method alone (ConfigInvocationHandler), not by plugin, so a setting
the separate plugins inherit from a shared interface (CommonConfig, BuffConfig) would read the same value in all
of them. Each plugin's settings interface therefore re-declares the shared settings it has, in a generated block
(same key, name and default: an override calling the shared one), which makes it its own method.
"""
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "src", "main", "java", "com", "bradsmultitool")
# Shared settings -> the plugin settings interfaces that re-declare them, each with the direct parent to call
SHARED = {
    "CommonConfig": [("SkillTrackerConfig", "CommonConfig"), ("PvmConfig", "CommonConfig"), ("GemCrabConfig", "CommonConfig"),
                     ("VoicesConfig", "CommonConfig"), ("BradsMultiToolConfig", "SkillTrackerConfig")],
    "BuffConfig": [("PvmConfig", "BuffConfig"), ("GemCrabConfig", "BuffConfig"), ("BradsMultiToolConfig", "PvmConfig")],
}
BEGIN = "    // ---- Generated by scripts/generate_config_defaults.py: %s's settings as this plugin's own (don't edit) ----\n"
END = "    // ---- End of %s's settings ----\n"

CONFIGS = ["CommonConfig", "TickConfig", "SkillTrackerConfig", "PvmConfig", "BuffConfig", "GemCrabConfig"]

TEMPLATE = """package com.bradsmultitool;

/**
 * Saves the default of every setting {name} declares, where nothing is saved yet (see ConfigDefaults).
 * Generated from {name}.java by scripts/generate_config_defaults.py: regenerate rather than editing.
 */
final class {name}Defaults {{

    private {name}Defaults() {{
    }}

    static void store(ConfigDefaults defaults, {name} config) {{
{lines}    }}
}}
"""


def without_generated(text):
    return re.sub(r"\n    // ---- Generated by scripts/generate_config_defaults\.py.*?// ---- End of \w+'s settings ----\n", "\n", text, flags=re.S)


def settings(name):
    """(keyName, method) of each @ConfigItem the interface declares itself (not its generated copies), in file order."""
    with open(os.path.join(SRC, name + ".java"), encoding="utf-8") as f:
        text = without_generated(f.read())
    found = []
    for item in re.finditer(r"@ConfigItem\((.*?)\)\s*(?:@\w+(?:\([^)]*\))?\s*)*default\s+[\w.<>, ]+?\s+(\w+)\(\)", text, re.S):
        key = re.search(r'keyName\s*=\s*"([^"]+)"', item.group(1)).group(1)
        found.append((key, item.group(2)))
    return found


def generate(name):
    lines = "".join('        defaults.store("%s", config.%s());\n' % (key, method) for key, method in settings(name))
    return TEMPLATE.format(name=name, lines=lines)


def item_chunks(name):
    """Each setting of a shared interface as written there: its annotations and method."""
    with open(os.path.join(SRC, name + ".java"), encoding="utf-8") as f:
        body = f.read()
    body = body[body.index("{", body.index("interface ")) + 1:body.rindex("}")]
    return [c.strip("\n") for c in body.split("\n\n") if "@ConfigItem(" in c and "default " in c]


def copies(shared, parent):
    """The shared interface's settings as overrides calling parent's."""
    out = []
    for chunk in item_chunks(shared):
        m = re.search(r"(\n    default ([\w.<>, ]+?) (\w+)\(\) \{.*\n    \})$", chunk, re.S)
        head = chunk[:m.start(1)]
        out.append("%s\n    @Override\n    default %s %s() {\n        return %s.super.%s();\n    }\n"
                   % (head, m.group(2), m.group(3), parent, m.group(3)))
    return "\n".join(out)


def with_copies(path, shared, parent):
    """The interface's source with the generated block of shared's settings (replaced, or added at the end)."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    block = BEGIN % shared + copies(shared, parent) + END % shared
    pattern = re.compile(re.escape(BEGIN % shared) + ".*?" + re.escape(END % shared), re.S)
    if pattern.search(text):
        return pattern.sub(lambda _: block, text)
    end = text.rindex("}")
    return text[:end].rstrip("\n") + "\n\n" + block + text[end:]


def main():
    stale = []
    for shared, targets in SHARED.items():
        for target, parent in targets:
            path = os.path.join(SRC, target + ".java")
            text = with_copies(path, shared, parent)
            with open(path, encoding="utf-8") as f:
                current = f.read()
            if current == text:
                continue
            if "--check" in sys.argv:
                stale.append(target + ".java (%s's settings)" % shared)
            else:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
                print("wrote %s's settings into %s" % (shared, target))
    for name in CONFIGS:
        path = os.path.join(SRC, name + "Defaults.java")
        text = generate(name)
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == text:
            continue
        if "--check" in sys.argv:
            stale.append(name + "Defaults.java")
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print("wrote %s (%d settings)" % (os.path.relpath(path, ROOT), len(settings(name))))
    if stale:
        raise SystemExit("Out of date: %s (run python3 scripts/generate_config_defaults.py)" % ", ".join(stale))


if __name__ == "__main__":
    main()
